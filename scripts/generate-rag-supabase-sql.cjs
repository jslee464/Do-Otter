/* eslint-disable @typescript-eslint/no-var-requires */
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

require.extensions[".ts"] = (module, filename) => {
  const source = fs.readFileSync(filename, "utf8");
  const output = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2019,
      esModuleInterop: true,
    },
    fileName: filename,
  }).outputText;
  module._compile(output, filename);
};

const { EVIDENCE } = require("../lib/rag/evidence.ts");
const {
  CHAT_SITUATION_IDS,
  SITUATIONS,
  ragSituations,
} = require("../lib/rag/situations.ts");

const outputPath = path.resolve(__dirname, "../supabase/rag_schema_and_seed.sql");
const chatIds = new Set(CHAT_SITUATION_IDS);

function text(value) {
  if (value === undefined || value === null) return "null";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function bool(value) {
  return value ? "true" : "false";
}

function textArray(values = []) {
  if (values.length === 0) return "'{}'::text[]";
  return `array[${values.map(text).join(", ")}]::text[]`;
}

function json(value) {
  return `${text(JSON.stringify(value))}::jsonb`;
}

const evidenceValues = EVIDENCE.map(
  (item) => `  (${[
    text(item.id),
    text(item.topic),
    text(item.domain),
    textArray(item.tags),
    text(item.evidenceLevel),
    text(item.sourceTitle),
    text(item.publisher),
    text(item.year),
    text(item.claim),
    text(item.usage),
    text(item.caution),
    text(item.url),
    text("do-otter-code"),
  ].join(", ")})`
).join(",\n");

const situationValues = SITUATIONS.map(
  (item) => `  (${[
    text(item.id),
    text(item.name),
    text(item.trigger),
    text(item.detectable),
    text(item.detectNote),
    text(item.answerType),
    bool(item.medical),
    text(item.purpose),
    text(item.template),
    text(item.expectedAction),
    text(item.generation),
    bool(chatIds.has(item.id)),
    bool(item.generation === "RAG+LLM" && item.evidenceIds.length > 0),
    text("do-otter-code"),
  ].join(", ")})`
).join(",\n");

const mappings = SITUATIONS.flatMap((situation) =>
  situation.evidenceIds.map((evidenceId, index) => ({
    situationId: situation.id,
    evidenceId,
    rank: index + 1,
  }))
);

const mappingValues = mappings
  .map(
    (item) =>
      `  (${text(item.situationId)}, ${text(item.evidenceId)}, ${item.rank}, 'do-otter-code')`
  )
  .join(",\n");

const evidenceIds = EVIDENCE.map((item) => text(item.id)).join(", ");
const situationIds = SITUATIONS.map((item) => text(item.id)).join(", ");

const sql = `-- ============================================================================
-- Do-Otter RAG schema + exact seed snapshot
-- Generated by: node scripts/generate-rag-supabase-sql.cjs
-- Source of truth: lib/rag/evidence.ts, lib/rag/situations.ts
-- Safe to run repeatedly: code-managed rows are synced without deleting external rows.
-- ============================================================================

begin;

-- 앱 기본 스키마가 이미 있다면 채팅 출처 메타데이터도 함께 마이그레이션한다.
-- chat_messages가 아직 없는 신규 프로젝트에서는 supabase/schema.sql 실행 시 생성된다.
do \$\$
begin
  if to_regclass('public.chat_messages') is not null then
    alter table public.chat_messages add column if not exists rag_meta jsonb;
  end if;
end
\$\$;

create table if not exists public.rag_evidence (
  id              text primary key check (id ~ '^R[1-9][0-9]*$'),
  topic           text not null,
  domain          text,
  tags            text[] not null default '{}',
  evidence_level  text,
  source_title    text not null,
  publisher       text not null,
  source_year     text not null,
  claim           text not null,
  usage           text not null,
  caution         text not null,
  url             text,
  managed_by      text not null default 'external',
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create table if not exists public.rag_situations (
  id               text primary key check (id ~ '^A[1-9][0-9]*$'),
  name             text not null,
  trigger_text     text not null,
  detectable       text not null,
  detect_note      text,
  answer_type      text not null,
  medical          boolean not null default false,
  purpose          text not null,
  template         text not null,
  expected_action  text not null,
  generation       text not null,
  chat_enabled     boolean not null default false,
  rag_enabled      boolean not null default false,
  managed_by       text not null default 'external',
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

create table if not exists public.rag_situation_evidence (
  situation_id  text not null references public.rag_situations(id) on delete cascade,
  evidence_id   text not null references public.rag_evidence(id) on delete cascade,
  rank          integer not null check (rank > 0),
  managed_by    text not null default 'external',
  created_at    timestamptz not null default now(),
  primary key (situation_id, evidence_id),
  unique (situation_id, rank)
);

create table if not exists public.rag_corpus_meta (
  corpus_key            text primary key,
  source_version        text not null,
  retrieval_mode        text not null,
  retrieval_weights     jsonb not null,
  emergency_situation   text not null references public.rag_situations(id),
  evidence_count        integer not null,
  situation_count       integer not null,
  rag_situation_count   integer not null,
  chat_situation_count  integer not null,
  mapping_count         integer not null,
  synced_at             timestamptz not null default now()
);

alter table public.rag_evidence
  add column if not exists managed_by text not null default 'external';
alter table public.rag_situations
  add column if not exists managed_by text not null default 'external';
alter table public.rag_situation_evidence
  add column if not exists managed_by text not null default 'external';

create index if not exists rag_evidence_domain_idx
  on public.rag_evidence(domain);
create index if not exists rag_evidence_tags_idx
  on public.rag_evidence using gin(tags);
create index if not exists rag_situations_rag_idx
  on public.rag_situations(rag_enabled, chat_enabled);
create index if not exists rag_mapping_evidence_idx
  on public.rag_situation_evidence(evidence_id);

insert into public.rag_evidence (
  id, topic, domain, tags, evidence_level, source_title, publisher, source_year,
  claim, usage, caution, url, managed_by
)
values
${evidenceValues}
on conflict (id) do update set
  topic = excluded.topic,
  domain = excluded.domain,
  tags = excluded.tags,
  evidence_level = excluded.evidence_level,
  source_title = excluded.source_title,
  publisher = excluded.publisher,
  source_year = excluded.source_year,
  claim = excluded.claim,
  usage = excluded.usage,
  caution = excluded.caution,
  url = excluded.url,
  managed_by = excluded.managed_by,
  updated_at = now();

insert into public.rag_situations (
  id, name, trigger_text, detectable, detect_note, answer_type, medical, purpose,
  template, expected_action, generation, chat_enabled, rag_enabled, managed_by
)
values
${situationValues}
on conflict (id) do update set
  name = excluded.name,
  trigger_text = excluded.trigger_text,
  detectable = excluded.detectable,
  detect_note = excluded.detect_note,
  answer_type = excluded.answer_type,
  medical = excluded.medical,
  purpose = excluded.purpose,
  template = excluded.template,
  expected_action = excluded.expected_action,
  generation = excluded.generation,
  chat_enabled = excluded.chat_enabled,
  rag_enabled = excluded.rag_enabled,
  managed_by = excluded.managed_by,
  updated_at = now();

delete from public.rag_situation_evidence where managed_by = 'do-otter-code';
insert into public.rag_situation_evidence (situation_id, evidence_id, rank, managed_by)
values
${mappingValues};

delete from public.rag_situations
where managed_by = 'do-otter-code' and id not in (${situationIds});
delete from public.rag_evidence
where managed_by = 'do-otter-code' and id not in (${evidenceIds});

insert into public.rag_corpus_meta (
  corpus_key, source_version, retrieval_mode, retrieval_weights,
  emergency_situation, evidence_count, situation_count, rag_situation_count,
  chat_situation_count, mapping_count, synced_at
)
values (
  'default',
  'R1-R${EVIDENCE.length}/A1-A${SITUATIONS.length}',
  'curated+keyword',
  ${json({ tags: 5, topic: 3, usage: 2, claim: 1, sourceTitle: 1, maxChatEvidence: 4 })},
  'A58',
  ${EVIDENCE.length},
  ${SITUATIONS.length},
  ${ragSituations().length},
  ${CHAT_SITUATION_IDS.length},
  ${mappings.length},
  now()
)
on conflict (corpus_key) do update set
  source_version = excluded.source_version,
  retrieval_mode = excluded.retrieval_mode,
  retrieval_weights = excluded.retrieval_weights,
  emergency_situation = excluded.emergency_situation,
  evidence_count = excluded.evidence_count,
  situation_count = excluded.situation_count,
  rag_situation_count = excluded.rag_situation_count,
  chat_situation_count = excluded.chat_situation_count,
  mapping_count = excluded.mapping_count,
  synced_at = excluded.synced_at;

alter table public.rag_evidence enable row level security;
alter table public.rag_situations enable row level security;
alter table public.rag_situation_evidence enable row level security;
alter table public.rag_corpus_meta enable row level security;

drop policy if exists "rag evidence read" on public.rag_evidence;
create policy "rag evidence read" on public.rag_evidence
  for select to anon, authenticated using (true);
drop policy if exists "rag situations read" on public.rag_situations;
create policy "rag situations read" on public.rag_situations
  for select to anon, authenticated using (true);
drop policy if exists "rag mapping read" on public.rag_situation_evidence;
create policy "rag mapping read" on public.rag_situation_evidence
  for select to anon, authenticated using (true);
drop policy if exists "rag corpus meta read" on public.rag_corpus_meta;
create policy "rag corpus meta read" on public.rag_corpus_meta
  for select to anon, authenticated using (true);

revoke insert, update, delete, truncate on public.rag_evidence from anon, authenticated;
revoke insert, update, delete, truncate on public.rag_situations from anon, authenticated;
revoke insert, update, delete, truncate on public.rag_situation_evidence from anon, authenticated;
revoke insert, update, delete, truncate on public.rag_corpus_meta from anon, authenticated;
grant select on public.rag_evidence to anon, authenticated;
grant select on public.rag_situations to anon, authenticated;
grant select on public.rag_situation_evidence to anon, authenticated;
grant select on public.rag_corpus_meta to anon, authenticated;

commit;

-- Verification query (expected: 38 / 60 / ${ragSituations().length} / ${CHAT_SITUATION_IDS.length} / ${mappings.length})
select
  (select count(*) from public.rag_evidence) as evidence_count,
  (select count(*) from public.rag_situations) as situation_count,
  (select count(*) from public.rag_situations where rag_enabled) as rag_situation_count,
  (select count(*) from public.rag_situations where chat_enabled) as chat_situation_count,
  (select count(*) from public.rag_situation_evidence) as mapping_count;
`;

fs.writeFileSync(outputPath, sql, "utf8");
console.log(
  `Generated ${path.relative(process.cwd(), outputPath)}: ` +
    `${EVIDENCE.length} evidence, ${SITUATIONS.length} situations, ${mappings.length} mappings.`
);
